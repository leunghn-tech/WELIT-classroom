function resolveDifficulty(profile, index, total) {
  const ratio = (index + 1) / Math.max(total, 1);
  if (profile === 'foundation') return ratio <= 0.6 ? '基礎' : '應用';
  if (profile === 'practice') return ratio <= 0.3 ? '基礎' : '應用';
  if (profile === 'reasoning') return ratio <= 0.3 ? '應用' : ratio <= 0.75 ? '進階' : '挑戰';
  return ratio <= 0.2 ? '應用' : ratio <= 0.65 ? '進階' : '挑戰';
}

